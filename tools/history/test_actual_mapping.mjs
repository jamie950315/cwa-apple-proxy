import fs from 'node:fs';
import assert from 'node:assert/strict';
import {transform} from '../mapper.mjs';
import {WeatherKit2,ByteBuffer} from '../vendor/weatherkit-codec.full.mjs';
const base='/home/jamie/cwa-weather-proxy/research';
const source=JSON.parse(fs.readFileSync(base+'/actual-brief.json')).source;
const original=new Uint8Array(fs.readFileSync(base+'/apple-'+source.id+'.bin'));
const r=await fetch('http://100.78.140.101:18880/v1/cwa/weather?latitude=25.090&longitude=121.560');
if(!r.ok)throw Error('CWA API '+r.status);
const snapshot=await r.json();
const {bytes,report}=transform(original,snapshot);
const roots=['currentWeather','forecastHourly','forecastDaily','locationInfo','airQuality'];
const before=WeatherKit2.decode(new ByteBuffer(original),roots),after=WeatherKit2.decode(new ByteBuffer(bytes),roots);
assert.equal(bytes.length,original.length);
assert.ok(report.modifiedFields>100);
assert.ok(Math.abs(after.currentWeather.temperature-snapshot.current.temperature)<0.0001);
assert.equal(after.currentWeather.humidity,Math.round(snapshot.current.humidity*100));
assert.deepEqual(before.airQuality,after.airQuality);
assert.deepEqual(before.locationInfo,after.locationInfo);
assert.equal(after.currentWeather.precipitationIntensity,before.currentWeather.precipitationIntensity);
assert.equal(after.currentWeather.pressure,before.currentWeather.pressure);
assert.throws(()=>transform(original,{...snapshot,current:{...snapshot.current,observationTime:1}}),/Stale/);
assert.throws(()=>transform(new Uint8Array([1,2,3]),snapshot),/Invalid/);
fs.writeFileSync(base+'/mapped-test.bin',bytes);
fs.writeFileSync(base+'/mapping-proof.json',JSON.stringify({passed:true,bytes:bytes.length,temperature:{apple:before.currentWeather.temperature,cwa:snapshot.current.temperature,mapped:after.currentWeather.temperature},humidity:{apple:before.currentWeather.humidity,cwa:snapshot.current.humidity,mapped:after.currentWeather.humidity},currentAfter:after.currentWeather,report},null,2));
console.log(JSON.stringify({passed:true,modified:report.modifiedFields,skipped:report.skippedFields,station:snapshot.location,temperature:after.currentWeather.temperature}));
